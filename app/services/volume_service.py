"""2D MPR backend prep (roadmap #26) — volume geometry + raw volume streaming.

**This module is a facade.** The implementation was split into
:mod:`app.services.volume` (FA-3):

| submodule            | owns                                              |
| -------------------- | ------------------------------------------------- |
| ``volume.slices``    | which instances form a volume, and in what order   |
| ``volume.assembly``  | the bundle (geometry + rows) and its cache keys    |
| ``volume.cache``     | the voxel cache (L1 memory + L2 Redis)             |
| ``volume.mpr``       | oblique/orthogonal resampling                      |
| ``volume.tiles``     | multi-slice PNG tiles                              |
| ``volume.mip``       | slab MIP / MinIP / average / VRT                   |
| ``volume.sessions``  | server-session accounting, viewer-mode decisions   |

Every public name is re-exported here, so ``volume_service.load_volume_array``
and the caches (``volume_service._VOL_CACHE`` …) are the *same objects* the
submodules use — tests that mutate or patch them keep working.
"""

